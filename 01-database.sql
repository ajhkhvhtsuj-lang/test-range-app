-- Supabase SQL Editor で一度だけ実行
create table if not exists public.study_push_subscriptions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  endpoint text not null unique,
  subscription jsonb not null,
  created_at timestamptz not null default now()
);
alter table public.study_push_subscriptions enable row level security;
drop policy if exists "push own select" on public.study_push_subscriptions;
create policy "push own select" on public.study_push_subscriptions for select to authenticated using (user_id=auth.uid());
drop policy if exists "push own insert" on public.study_push_subscriptions;
create policy "push own insert" on public.study_push_subscriptions for insert to authenticated with check (user_id=auth.uid());
drop policy if exists "push own update" on public.study_push_subscriptions;
create policy "push own update" on public.study_push_subscriptions for update to authenticated using (user_id=auth.uid()) with check (user_id=auth.uid());
drop policy if exists "push own delete" on public.study_push_subscriptions;
create policy "push own delete" on public.study_push_subscriptions for delete to authenticated using (user_id=auth.uid());

-- 通知の重複を防ぐ記録
create table if not exists public.study_push_deliveries (
  user_id uuid not null references auth.users(id) on delete cascade,
  notification_key text not null,
  sent_at timestamptz not null default now(),
  primary key (user_id, notification_key)
);
alter table public.study_push_deliveries enable row level security;
-- deliveries はサーバーの service_role だけが操作する

-- チャットのまとめ通知用の記録
create table if not exists public.study_chat_push_state (
  user_id uuid not null references auth.users(id) on delete cascade,
  group_id uuid not null references public.study_groups(id) on delete cascade,
  last_notified_at timestamptz not null default '1970-01-01',
  primary key(user_id, group_id)
);
alter table public.study_chat_push_state enable row level security;
